-- Create one private profile for existing Auth users and future users via trigger.
CREATE OR REPLACE FUNCTION public.maestria_sync_auth_user_profile()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  INSERT INTO public.user_profile (user_id, email, full_name, role, status)
  VALUES (
    NEW.id,
    lower(coalesce(NEW.email, '')),
    left(coalesce(NEW.raw_user_meta_data ->> 'full_name', NEW.raw_user_meta_data ->> 'name', ''), 180),
    'teacher', 'active'
  )
  ON CONFLICT (user_id) DO UPDATE
    SET email = EXCLUDED.email,
        full_name = CASE WHEN public.user_profile.full_name = '' THEN EXCLUDED.full_name ELSE public.user_profile.full_name END,
        updated_at = now();
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS maestria_auth_user_profile_insert ON auth.users;
CREATE TRIGGER maestria_auth_user_profile_insert AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.maestria_sync_auth_user_profile();
DROP TRIGGER IF EXISTS maestria_auth_user_profile_update ON auth.users;
CREATE TRIGGER maestria_auth_user_profile_update AFTER UPDATE OF email, raw_user_meta_data ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.maestria_sync_auth_user_profile();
INSERT INTO public.user_profile (user_id, email, full_name, role, status)
SELECT u.id, lower(coalesce(u.email, '')),
       left(coalesce(u.raw_user_meta_data ->> 'full_name', u.raw_user_meta_data ->> 'name', ''), 180),
       'teacher', 'active'
FROM auth.users u
ON CONFLICT (user_id) DO NOTHING;

