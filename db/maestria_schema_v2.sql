CREATE OR REPLACE FUNCTION public.maestria_validate_submission_question()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.question_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.question q WHERE q.id = NEW.question_id
      AND q.assessment_id = NEW.assessment_id AND q.owner_id = NEW.owner_id
  ) THEN
    RAISE EXCEPTION 'La pregunta debe pertenecer a la evaluación de la entrega y al mismo propietario' USING ERRCODE = '23503';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER submission_question_same_assessment
BEFORE INSERT OR UPDATE OF assessment_id, question_id, owner_id ON public.submission
FOR EACH ROW EXECUTE FUNCTION public.maestria_validate_submission_question();

CREATE OR REPLACE FUNCTION public.maestria_validate_submission_answer_question()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.submission s JOIN public.question q ON q.id = NEW.question_id
    WHERE s.id = NEW.submission_id AND s.assessment_id = q.assessment_id
      AND s.owner_id = NEW.owner_id AND q.owner_id = NEW.owner_id
  ) THEN
    RAISE EXCEPTION 'La pregunta debe pertenecer a la evaluación de la entrega y al mismo propietario' USING ERRCODE = '23503';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER submission_answer_question_same_assessment
BEFORE INSERT OR UPDATE OF submission_id, question_id, owner_id ON public.submission_answer
FOR EACH ROW EXECUTE FUNCTION public.maestria_validate_submission_answer_question();

CREATE OR REPLACE FUNCTION public.maestria_validate_correction_result_question()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.question_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.correction c JOIN public.submission s ON s.id = c.submission_id
    JOIN public.question q ON q.id = NEW.question_id
    WHERE c.id = NEW.correction_id AND s.assessment_id = q.assessment_id
      AND c.owner_id = NEW.owner_id AND q.owner_id = NEW.owner_id
  ) THEN
    RAISE EXCEPTION 'La pregunta del resultado debe pertenecer a la evaluación de la entrega corregida' USING ERRCODE = '23503';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER correction_result_question_same_assessment
BEFORE INSERT OR UPDATE OF correction_id, question_id, owner_id ON public.correction_criterion_result
FOR EACH ROW EXECUTE FUNCTION public.maestria_validate_correction_result_question();

CREATE OR REPLACE FUNCTION public.maestria_validate_rubric_level_score()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE max_allowed numeric;
BEGIN
  SELECT max_score INTO max_allowed FROM public.rubric_criterion
  WHERE id = NEW.criterion_id AND owner_id = NEW.owner_id FOR UPDATE;
  IF max_allowed IS NULL OR NEW.score > max_allowed THEN
    RAISE EXCEPTION 'El nivel debe pertenecer al criterio y no superar su puntuación máxima' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER rubric_level_score_within_criterion
BEFORE INSERT OR UPDATE OF criterion_id, owner_id, score ON public.rubric_level
FOR EACH ROW EXECUTE FUNCTION public.maestria_validate_rubric_level_score();

CREATE OR REPLACE FUNCTION public.maestria_validate_criterion_max_score()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM public.rubric_level l WHERE l.criterion_id = NEW.id AND l.score > NEW.max_score) THEN
    RAISE EXCEPTION 'El máximo del criterio no puede ser menor que la puntuación de un nivel existente' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER rubric_criterion_max_score_consistency
BEFORE UPDATE OF max_score ON public.rubric_criterion
FOR EACH ROW EXECUTE FUNCTION public.maestria_validate_criterion_max_score();

