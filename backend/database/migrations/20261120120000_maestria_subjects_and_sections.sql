-- 7. Seguridad: RLS, políticas y permisos con el mismo esquema que el resto -------
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['subject', 'assessment_course', 'external_link'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_owner_isolation', t);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I TO authenticated USING ((SELECT auth.uid()) = owner_id) WITH CHECK ((SELECT auth.uid()) = owner_id)',
      t || '_owner_isolation', t
    );
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'maestria_app') THEN
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO maestria_app', t);
      EXECUTE format('DROP POLICY IF EXISTS maestria_app_backend_access ON public.%I', t);
      EXECUTE format('CREATE POLICY maestria_app_backend_access ON public.%I FOR ALL TO maestria_app USING (true) WITH CHECK (true)', t);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'maestria_app') THEN
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO maestria_app;
  END IF;
  -- Igual que las demás tablas de negocio: el acceso directo de anon/authenticated
  -- no tiene permisos (todo pasa por la API).
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.subject, public.assessment_course, public.external_link FROM anon, authenticated;
  END IF;
END $$;

-- 8. Backfill (sólo lo que todavía está vacío) ------------------------------------
-- Una materia por cada nombre distinto de materia (o del curso, si no tenía materia).
INSERT INTO public.subject (owner_id, name, level, created_at, updated_at)
SELECT DISTINCT ON (c.owner_id, lower(btrim(COALESCE(NULLIF(btrim(c.subject), ''), c.name))))
       c.owner_id,
       left(btrim(COALESCE(NULLIF(btrim(c.subject), ''), c.name)), 160),
       c.level, c.created_at, now()
FROM public.course c
WHERE c.subject_id IS NULL
ORDER BY c.owner_id, lower(btrim(COALESCE(NULLIF(btrim(c.subject), ''), c.name))), c.created_at
ON CONFLICT (owner_id, lower(name::text)) DO NOTHING;

UPDATE public.course c
SET subject_id = s.id
FROM public.subject s
WHERE c.subject_id IS NULL
  AND s.owner_id = c.owner_id
  AND lower(s.name) = lower(left(btrim(COALESCE(NULLIF(btrim(c.subject), ''), c.name)), 160));

-- Evaluaciones sin curso pero con materia escrita: se reutiliza o se crea la materia.
INSERT INTO public.subject (owner_id, name, level)
SELECT DISTINCT ON (a.owner_id, lower(btrim(a.subject))) a.owner_id, left(btrim(a.subject), 160), a.level
FROM public.assessment a
WHERE a.subject_id IS NULL AND a.course_id IS NULL AND btrim(a.subject) <> ''
ORDER BY a.owner_id, lower(btrim(a.subject)), a.created_at
ON CONFLICT (owner_id, lower(name::text)) DO NOTHING;

UPDATE public.assessment a
SET subject_id = c.subject_id
FROM public.course c
WHERE a.subject_id IS NULL AND a.course_id = c.id AND a.owner_id = c.owner_id;

UPDATE public.assessment a
SET subject_id = s.id
FROM public.subject s
WHERE a.subject_id IS NULL AND a.course_id IS NULL AND btrim(a.subject) <> ''
  AND s.owner_id = a.owner_id AND lower(s.name) = lower(left(btrim(a.subject), 160));

INSERT INTO public.assessment_course (owner_id, assessment_id, course_id, created_at)
SELECT a.owner_id, a.id, a.course_id, a.created_at
FROM public.assessment a
WHERE a.course_id IS NOT NULL
ON CONFLICT (assessment_id, course_id) DO NOTHING;

UPDATE public.submission sub
SET course_id = a.course_id
FROM public.assessment a
WHERE sub.course_id IS NULL AND sub.assessment_id = a.id AND sub.owner_id = a.owner_id AND a.course_id IS NOT NULL;

COMMENT ON TABLE public.subject IS 'Materia del docente; agrupa sus cursos o comisiones.';
COMMENT ON TABLE public.assessment_course IS 'Comisiones a las que se asignó una evaluación de la materia.';
COMMENT ON TABLE public.external_link IS 'Identificadores en plataformas externas (Moodle, Google Classroom, SIU Guaraní/CSV, Google Drive).';
COMMENT ON COLUMN public.submission.course_id IS 'Comisión en la que se registró la entrega.';

COMMIT;
