-- Migration 20261120120000 / maestria_subjects_and_sections
-- Fase 1: Materias y comisiones.
--
-- Hasta ahora `course` mezclaba la materia (texto libre en course.subject, repetido en
-- assessment.subject) con el curso o comisión: quien dicta Programación I en tres
-- comisiones tenía que crear tres «cursos» y repetir las evaluaciones en cada uno.
--
-- Modelo nuevo:
--   subject            la materia del docente (Programación I).
--   course.subject_id  cada curso/comisión pertenece a una materia (1K1, 1K2, noche…).
--   course.shift       turno de la comisión (opcional).
--   assessment.subject_id + assessment_course
--                      la evaluación es de la materia y se asigna a una o más comisiones.
--   rubric.subject_id  biblioteca de rúbricas por materia (opcional).
--   submission.course_id
--                      comisión en la que se entregó (las notas son por comisión).
--   external_link      vínculos con plataformas externas (Moodle, Google Classroom,
--                      SIU Guaraní/CSV, Google Drive) para las integraciones siguientes.
--
-- Es ADITIVA y compatible con la versión desplegada: no borra ni renombra columnas.
-- course.subject, assessment.subject/level y assessment.course_id se conservan; el
-- código nuevo los sigue escribiendo y se podrán eliminar en una migración posterior.
-- Idempotente: se puede ejecutar más de una vez (el backfill sólo completa lo vacío).

BEGIN;

-- 1. Materias ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.subject (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  name varchar(160) NOT NULL,
  level varchar(120) NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT subject_name_not_blank CHECK (btrim(name) <> '')
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'core_subject_owner_auth_user_fk') THEN
    ALTER TABLE public.subject
      ADD CONSTRAINT core_subject_owner_auth_user_fk FOREIGN KEY (owner_id) REFERENCES auth.users(id) ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_subject_id_owner') THEN
    ALTER TABLE public.subject ADD CONSTRAINT uq_subject_id_owner UNIQUE (id, owner_id);
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uniq_subject_owner_name_ci ON public.subject (owner_id, lower(name::text));
CREATE INDEX IF NOT EXISTS subject_owner_active_idx ON public.subject (owner_id, active);

DROP TRIGGER IF EXISTS subject_touch_updated_at ON public.subject;
CREATE TRIGGER subject_touch_updated_at BEFORE UPDATE ON public.subject
  FOR EACH ROW EXECUTE FUNCTION public.maestria_touch_updated_at();

-- 2. Comisión: materia y turno ---------------------------------------------------
ALTER TABLE public.course ADD COLUMN IF NOT EXISTS subject_id bigint;
