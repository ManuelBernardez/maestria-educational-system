CREATE INDEX IF NOT EXISTS ix_course_subject_owner ON public.course (subject_id, owner_id);

-- El nombre del curso pasa a ser el de la comisión («1K1»): se puede repetir en otra
-- materia o en otro ciclo lectivo. Este índice es más permisivo que el anterior, así
-- que la versión desplegada (que valida nombres únicos por docente) sigue funcionando.
CREATE UNIQUE INDEX IF NOT EXISTS uniq_course_owner_subject_name_year_ci
  ON public.course (owner_id, COALESCE(subject_id, 0), lower(name::text), academic_year);
DROP INDEX IF EXISTS public.uniq_course_owner_name_ci;

